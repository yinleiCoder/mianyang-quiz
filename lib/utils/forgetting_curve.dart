// 艾宾浩斯遗忘曲线的**理论值**：一条常量曲线，用来跟学生自己的实测保持率对比。
//
// 为什么在客户端而不是服务端：迁移 0067 写明了——「理论曲线（艾宾浩斯）是常量，
// 画在图里即可，不进数据库」。它跟任何用户数据无关，存一遍反而多一份要同步的东西。
//
// 纯 Dart，无 Flutter 依赖，可独立单测。

import 'dart:math' as math;

// ---------------------------------------------------------------------------
// 一条重要的口径提醒（别让这张图误导学生）
// ---------------------------------------------------------------------------
// 艾宾浩斯当年用的是**无意义音节**，所以那条曲线掉得很陡（1 天只剩 33%）。
// 而这里练的是有意义的专业课题目，实测保持率**几乎必然高于理论线**。
// 所以这张图要读的是**形状**，不是"我达标了没有"：
//   · 实测线是否也在下降？降得比理论线快还是慢？
//   · 哪个间隔档上掉得最狠？那一档就是该缩短复习间隔的地方。
// 图注里必须把这件事说清楚，否则学生只会看到"我比艾宾浩斯强"，等于没看。

/// 经典艾宾浩斯保持率锚点（天 → 保持率）。
///
/// 取自被引用最广的那组数（20 分钟 58%、1 小时 44%、9 小时 36%、1 天 33%、
/// 2 天 28%、6 天 25%、31 天 21%），两端补上 0 天的 100%。
/// **不要随手改**：改了整条理论线就跟着变，而它唯一的用处就是当参照物。
const List<(double, double)> _anchors = [
  (0, 1.00),
  (20 / 1440, 0.58), // 20 分钟
  (1 / 24, 0.44), // 1 小时
  (9 / 24, 0.36), // 9 小时
  (1, 0.33),
  (2, 0.28),
  (6, 0.25),
  (31, 0.21),
];

/// 31 天之后不再往下掉：经典那组数到 21% 就基本走平了。
/// 若继续按前面的斜率外推，60 天会掉到 15% 以下，那是编出来的数。
const double _floor = 0.21;

/// 距学完 [days] 天后的理论保持率（0~1）。[days] 为负按 0 处理。
///
/// 在**对数时间轴**上做线性插值：遗忘曲线在短时间内掉得极快、之后趋缓，
/// 用线性轴插值会把前 1 小时那段画成一条几乎垂直的线，看不出层次。
double ebbinghausRetention(double days) {
  final t = days <= 0 ? 0.0 : days;
  if (t >= _anchors.last.$1) return _floor;

  for (var i = 1; i < _anchors.length; i++) {
    final (x1, y1) = _anchors[i];
    if (t > x1) continue;

    final (x0, y0) = _anchors[i - 1];
    // 0 天与 20 分钟之间取线性：对数轴在 0 处没定义
    final ratio = x0 == 0
        ? t / x1
        : (math.log(t) - math.log(x0)) / (math.log(x1) - math.log(x0));
    return y0 + (y1 - y0) * ratio;
  }
  return _floor;
}

/// 画理论线用的采样点：0~[maxDays] 天均匀取 [count] 段。
///
/// 采样要密：这条线在对数轴上弯曲，点太少会画成折线。
List<(double, double)> ebbinghausSamples({
  double maxDays = 30,
  int count = 96,
}) => [
  for (var i = 0; i <= count; i++)
    (
      maxDays * i / count,
      ebbinghausRetention(maxDays * i / count),
    ),
];
